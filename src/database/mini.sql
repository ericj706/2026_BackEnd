CREATE TABLE CLOTHESSYMBOLLIST (
    CLOTHESID INT,
    SYMBOLID INT,

    CONSTRAINT FOREIGN KEY (CLOTHESID) REFERENCES CLOTHES(CLOTHESID),
     CONSTRAINT FOREIGN KEY (SYMBOLID) REFERENCES SYMBOL(SYMBOLID)
);

CREATE TABLE CLOTHESDRYINGLIST(
    CLOTHESID INT,
    DRYID INT,

    CONSTRAINT FOREIGN KEY (CLOTHESID) REFERENCES CLOTHES(CLOTHESID),
    CONSTRAINT FOREIGN KEY (DRYID) REFERENCES DRY(DRYID)
);
